    private void txtIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActionPerformed
String id=txtId.getText();

        try {Connection con;
            con=DriverManager.getConnection("jdbc:mysql://localhost:3306/emp", "root", "sehrish1106");
                   String qry="SELECT * FROM `employee` WHERE `emp_id`=?";
                   PreparedStatement ps=con.prepareStatement(qry);
                   ps.setString(1, id);
                   ResultSet rs=ps.executeQuery();
                   if(rs.next()){
                   String name=rs.getString("emp_Name");
                   String contact_no=rs.getString("emp_phone_Number");
                   String salary=rs.getString("emp_Salary");
                   txtName.setText(name);
                   txtContactNumber.setText(contact_no);
                   txtSalary.setText(salary);
                   }
con.close();
        } catch (SQLException ex) {
            Logger.getLogger(Employee.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_txtIdActionPerformed

