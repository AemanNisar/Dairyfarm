    private void txtIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtIdActionPerformed
 String id=txtId.getText();

        try {
            Connection con=DriverManager.getConnection("jdbc:mysql://localhost:3306/dairyfarm", "root", "aeman");
        String qry="SELECT * FROM `cow` WHERE `cow_id`=?";
        PreparedStatement ps=con.prepareStatement(qry);
         ps.setString(1, id);
                   ResultSet rs=ps.executeQuery();
                   if(rs.next()){
                   String weight=rs.getString("cow_weight");
                   String milk=rs.getString("cow_milk_production_per_day");
                   String money=rs.getString("money_spent_on_cow");
                   txtWeight.setText(weight);
                   txtMilkProduction.setText(milk);
                   txtMoneySpent.setText(money);
                   }
        
        } catch (SQLException ex) {
            Logger.getLogger(UpdateCustomerInfo.class.getName()).log(Level.SEVERE, null, ex);
        }    }//GEN-LAST:event_txtIdActionPerformed

