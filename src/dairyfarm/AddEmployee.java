    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed

if (txtName.getText().isEmpty() || txtContactNumber.getText().isEmpty() || txtSalary.getText().isEmpty())
   {
   JOptionPane.showMessageDialog(null, "Please fill in all fields", "Error", 1);
   }
else{
    String name = txtName.getText();

String contact_no = txtContactNumber.getText();
Double salary = Double.parseDouble(txtSalary.getText());
Employee employee = new Employee();
employee.addEmployee( name, contact_no, salary);
 JOptionPane.showMessageDialog(null, "Successfully added", "", 1);
  txtName.setText("");
  txtContactNumber.setText("");
  txtSalary.setText("");
}
    }//GEN-LAST:event_jButton2ActionPerformed

